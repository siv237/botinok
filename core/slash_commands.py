# -*- coding: utf-8 -*-
"""Единый реестр slash-команд TUI.

Два потребителя из одного источника:
- `/help` в `_handle_slash_command` (`core/textual_integration.py`)
  печатает строки реестра — описания не расходятся;
- Composer (`core/textual_app.py`) показывает фильтруемый список при вводе
  «/»: набор знаков сокращает список, ↓/↑ ходят по кандидатам, Tab/Enter
  дописывают выбранную команду.

`args` — подсказка аргументов только для показа (без скобок: строка уезжает
в rich-разметку `/help`, а `[...]` rich читает как тег стиля). Вставка по
выбору всегда заканчивается пробелом: список закрывается, а Enter отправляет
команду (пустые аргументы `action_submit` просто срезает).
"""

# (имя без слэша, подсказка аргументов для показа, описание)
SLASH_COMMANDS = (
    ("help", "", "показать список команд"),
    ("model", "<name>", "сменить модель (например /model qwen3.5:9b)"),
    ("models", "", "список доступных моделей"),
    ("ctx", "<n>", "сменить размер контекста (например /ctx 32768)"),
    ("key", "", "ввести или сменить API-ключ"),
    ("info", "", "сведения о сессии: сервер, модель, ключ, тема"),
    ("tools", "", "каталог инструментов агента"),
    ("theme", "имя", "тема: ночь/день/вечер; без имени — следующая по циклу"),
    ("reasoning", "", "окно выбора режима рассуждения"),
    ("proofread", "", "переключить режим корректора Исполнитель → Корректор"),
    ("clear", "", "очистить экран"),
    ("dangerous", "", "перекключить опасный режим"),
    ("retry", "", "повторить последний запрос"),
    ("vram", "", "показать статус VRAM"),
)


def command_label(entry) -> str:
    """Метка для показа: `/model <name>`."""
    name, args, _desc = entry
    return f"/{name} {args}".rstrip()


def command_completion(entry) -> str:
    """Текст вставки в Composer: всегда с пробелом — список закрывается."""
    return f"/{entry[0]} "


def prefix_matches(text: str) -> list:
    """Команды под введённый префикс. "/" — все; пробел/перенос строки
    (аргументы, многострочность) — список скрыт; обычный текст — пусто."""
    text = text or ""
    if not text.startswith("/"):
        return []
    if any(ch.isspace() for ch in text):
        return []
    query = text[1:].lower()
    return [e for e in SLASH_COMMANDS if e[0].startswith(query)]


def help_rows() -> list:
    """Строки для /help: (метка, описание) в порядке реестра."""
    return [(command_label(e), e[2]) for e in SLASH_COMMANDS]